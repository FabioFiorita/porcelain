import { createHash } from 'node:crypto'
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const checkout = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const [operation, suppliedRoot, generated] = process.argv.slice(2)
if (process.platform !== 'win32') throw new Error('This helper is for native Windows builds.')
if (!suppliedRoot || !isAbsolute(suppliedRoot))
  throw new Error('Supply an absolute task-owned staging directory.')
const stage = resolve(suppliedRoot)
if (dirname(stage) === stage || checkout === stage || checkout.startsWith(stage + sep)) {
  throw new Error('Staging must not be a filesystem root, checkout, or checkout ancestor.')
}
const marker = join(stage, 'porcelain-native-owner.json')
mkdirSync(stage, { recursive: true })
if (existsSync(marker)) {
  if (JSON.parse(readFileSync(marker, 'utf8')).checkout !== checkout)
    throw new Error('Staging belongs to another checkout.')
} else {
  if (readdirSync(stage).length !== 0)
    throw new Error('Choose an empty task-owned staging directory.')
  writeFileSync(marker, JSON.stringify({ checkout }, null, 2) + '\n')
}
if (operation === 'prepare') process.exit(0)
if (operation !== 'rewrite') throw new Error('Expected prepare or rewrite.')
const expected = join(
  checkout,
  'apps/mobile/android/app/build/generated/autolinking/src/main/jni/Android-autolinking.cmake',
)
if (!generated || resolve(generated) !== expected)
  throw new Error('Unexpected generated CMake file.')
const content = readFileSync(expected, 'utf8')
const entries = [...content.matchAll(/^add_subdirectory\("([^"]+)" ([^)]+)\)$/gm)]
if (
  !content.includes('This code was generated by [React Native]') ||
  entries.length === 0 ||
  entries.length !== (content.match(/add_subdirectory\(/g) ?? []).length
) {
  throw new Error('Generated autolinking format changed; inspect before adapting it.')
}
let updated = content
const aliases = []
for (const [, source] of entries) {
  const offset = source.lastIndexOf('/android/')
  if (offset < 0 || !isAbsolute(source))
    throw new Error(`Unexpected Android module path: ${source}`)
  const target = source.slice(0, offset)
  const local = relative(checkout, target)
  if (local.startsWith('..') || isAbsolute(local))
    throw new Error(`Module is outside checkout: ${target}`)
  const id = createHash('sha256').update(target).digest('hex').slice(0, 10)
  const alias = join(stage, 'sources', id)
  mkdirSync(dirname(alias), { recursive: true })
  if (existsSync(alias)) {
    if (!lstatSync(alias).isSymbolicLink() || realpathSync(alias) !== realpathSync(target))
      throw new Error(`Alias conflict: ${alias}`)
  } else {
    symlinkSync(target, alias, 'junction')
  }
  updated = updated.replaceAll(source, alias.replaceAll('\\', '/') + source.slice(offset))
  aliases.push({ alias, target, source })
}
writeFileSync(expected, updated)
writeFileSync(join(stage, 'source-aliases.json'), JSON.stringify(aliases, null, 2) + '\n')
